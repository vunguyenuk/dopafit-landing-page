/* Independent introduction; never owns the old hero, fan, phone or scroll driver.
   The 3s video track is baked in Blender, not generated by a new CSS rotation. */
const section=document.getElementById('dopafit-intro');
if(section){
  const host=section.querySelector('.intro-phone');
  const title=section.querySelector('.intro-title'),description=section.querySelector('.intro-description'),proof=section.querySelector('.intro-proof');
  const clamp=x=>Math.max(0,Math.min(1,x));
  const smooth=x=>{x=clamp(x);return x*x*(3-2*x);};
  // Source: dropset-tracking-source.js a-55 Content, a-55-n / a-55-n-2:
  // fade in and move 80 design px → 0. Extend the old .30s scroll window;
  // overlap groups while preserving their final Figma positions.
  const move=window.DopafitDropsetActions?.['a-55']?.continuousParameterGroups[0].continuousActionGroups[0].actionItems.find(item=>item.actionTypeId==='TRANSFORM_MOVE');
  section.style.setProperty('--intro-copy-rise',`${move?.config.yValue??80}`);
  const reveal=(el,clock,start)=>{
    const alpha=reduced?1:smooth((clock-start)/.65),settle=reduced?1:smooth((clock-start)/.80);
    el.style.opacity=String(alpha);el.style.visibility=alpha>0?'visible':'hidden';
    el.style.setProperty('--intro-copy-settle',String(settle));
    return settle;
  };
  const reduced=matchMedia('(prefers-reduced-motion: reduce)').matches||new URLSearchParams(location.search).get('motion')==='off';
  section.querySelector('.intro-download').addEventListener('click',()=>document.getElementById('download-dialog')?.showModal());
  let sample,frame=0,visible=true,progress=0;
  function update(){
    frame=0;
    if(!visible)return;
    const bounds=section.getBoundingClientRect(),travel=section.offsetHeight-section.firstElementChild.clientHeight;
    progress=reduced?.5:Math.max(0,Math.min(1,-bounds.top/Math.max(1,travel)));
    section.dataset.progress=progress.toFixed(5);section.dataset.clock=(progress*3).toFixed(4);
    const clock=progress*3;
    // Reference order: phone first, then lower it to make room for the copy.
    // Keep the existing Blender angle/scale track and accepted final Figma slots.
    const lowered=reduced?1:smooth((clock-.15)/.90);
    section.style.setProperty('--intro-lowered',String(lowered));
    reveal(title,clock,.50);
    reveal(description,clock,.66);
    const proofSettled=reveal(proof,clock,.82);proof.inert=proofSettled<1;
    section.dataset.stage=reduced?'copy':clock<=.15?'phone':clock<1.62?'lowering':'copy';
    sample?.(progress*3);
  }
  const request=()=>{if(!frame)frame=requestAnimationFrame(update);};
  new IntersectionObserver(([entry])=>{visible=entry.isIntersecting;if(visible)request();}).observe(section);
  addEventListener('scroll',request,{passive:true});addEventListener('resize',request,{passive:true});addEventListener('dopafit:scroll',request);
  if(!reduced){
    import('./phone-scene.js?v=20261123-perf').then(m=>m.mountIntroPhone(host)).then(render=>{sample=render;request();}).catch(error=>{host.dataset.fallback=error.message;console.warn('Intro retains the Blender poster:',error);});
  }else{host.dataset.reduced='true';host.querySelector('img').src='assets/intro/phone-poster-settled.webp?v=framing-3';}
  update();
}
